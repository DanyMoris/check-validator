def build_story(styles) -> list:
    story: list = [
        Paragraph("Сервис проверки банковских чеков", styles["title"]),
        Paragraph("Как устроена проверка подлинности и как защищены данные", styles["subtitle"]),
        spec_banner(styles),
        Spacer(1, 12),
    ]
    for kind, text in CONTENT:
        if kind == "h2":
            story.append(Paragraph(text, styles["h2"]))
        elif kind == "p":
            story.append(Paragraph(text, styles["body"]))
        elif kind == "li":
            story.append(Paragraph(text, styles["bullet"], bulletText="•"))
        elif kind == "note":
            story.append(Spacer(1, 5))
            story.append(Paragraph(text, styles["note"]))
        elif kind == "panel":
            story.append(Spacer(1, 3))
            story.append(panel_block(text, styles))
            story.append(Spacer(1, 8))
        elif kind == "verdict":
            story.append(KeepTogether(verdict_block(text, styles)))
    return story


def make_footer(styles):
    def footer(canvas, doc):
        canvas.saveState()
        canvas.setStrokeColor(RULE)
        canvas.setLineWidth(0.5)
        canvas.line(23 * mm, 17 * mm, 187 * mm, 17 * mm)
        label = Paragraph(f"Стр. {doc.page}", styles["footer"])
        label.wrapOn(canvas, 164 * mm, 10 * mm)
        label.drawOn(canvas, 23 * mm, 11 * mm)
        canvas.restoreState()

    return footer


def main() -> None:
    register_fonts()
    styles = build_styles()
    OUT.parent.mkdir(parents=True, exist_ok=True)

    doc = BaseDocTemplate(
        str(OUT),
        pagesize=A4,
        leftMargin=23 * mm,
        rightMargin=24 * mm,
        topMargin=22 * mm,
        bottomMargin=24 * mm,
        title="Сервис проверки банковских чеков — описание работы",
        author="",
        subject="Описание принципов проверки подлинности и защиты данных",
    )
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="main")
    doc.addPageTemplates([PageTemplate(id="main", frames=[frame], onPage=make_footer(styles))])
    doc.build(build_story(styles))
    print(f"Готово: {OUT}")


if __name__ == "__main__":
    main()
