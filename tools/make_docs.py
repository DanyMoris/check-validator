def register_fonts() -> None:
    """Берём шрифты из системных Windows — без загрузки и внешних зависимостей."""
    missing = [f for f in FONT_FILES.values() if not (WINDOWS_FONTS / f).exists()]
    if missing:
        sys.exit(f"Не найдены шрифты в {WINDOWS_FONTS}: {', '.join(missing)}")
    for name, filename in FONT_FILES.items():
        pdfmetrics.registerFont(TTFont(name, str(WINDOWS_FONTS / filename)))
    pdfmetrics.registerFontFamily(
        "UI", normal="UI", bold="UI-Bold", italic="UI-Italic", boldItalic="UI-Bold"
    )


